-- team_color_master に link 列を register_id の前に追加する（作り直し。2026-11-24）
-- 1 トランザクション。失敗したら何も変わらない。今の列定義・インデックス・主キー・データはそのまま引き継ぐ。
BEGIN;
LOCK TABLE team_color_master IN ACCESS EXCLUSIVE MODE;

DO $$
DECLARE
  r record;
  defs text := '';
  cols text := '';
  sel  text := '';
  has_link boolean;
  idx  record;
  pk_cols text;
  maxid bigint;
BEGIN
  SELECT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema = current_schema() AND table_name = 'team_color_master' AND column_name = 'link')
    INTO has_link;

  FOR r IN
    SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS typ, a.attnotnull, a.attidentity,
           pg_get_expr(d.adbin, d.adrelid) AS def
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
     WHERE a.attrelid = 'team_color_master'::regclass AND a.attnum > 0 AND NOT a.attisdropped
       AND a.attname <> 'link'
     ORDER BY a.attnum
  LOOP
    IF r.attname = 'register_id' THEN
      defs := defs || 'link VARCHAR(2048), ';
      cols := cols || 'link, ';
      sel  := sel  || CASE WHEN has_link THEN 'link, ' ELSE 'NULL, ' END;
    END IF;
    defs := defs || quote_ident(r.attname) || ' ' || r.typ
                 || CASE r.attidentity WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
                                        WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' ELSE '' END
                 || CASE WHEN r.attnotnull THEN ' NOT NULL' ELSE '' END
                 || CASE WHEN r.def IS NOT NULL AND r.attidentity = '' THEN ' DEFAULT ' || r.def ELSE '' END
                 || ', ';
    cols := cols || quote_ident(r.attname) || ', ';
    sel  := sel  || quote_ident(r.attname) || ', ';
  END LOOP;
  IF position('link VARCHAR' in defs) = 0 THEN
    RAISE EXCEPTION 'register_id 列が見つかりません';
  END IF;
  defs := left(defs, length(defs) - 2);
  cols := left(cols, length(cols) - 2);
  sel  := left(sel,  length(sel)  - 2);

  EXECUTE 'CREATE TABLE team_color_master_new (' || defs || ')';
  EXECUTE 'INSERT INTO team_color_master_new (' || cols || ') OVERRIDING SYSTEM VALUE SELECT ' || sel || ' FROM team_color_master';

  -- 主キー
  SELECT string_agg(quote_ident(a.attname), ', ' ORDER BY array_position(i.indkey::int2[], a.attnum))
    INTO pk_cols
    FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey)
   WHERE i.indrelid = 'team_color_master'::regclass AND i.indisprimary;

  -- 元のインデックス定義（主キー以外）を控えてから入れ替える
  CREATE TEMP TABLE _tcm_idx ON COMMIT DROP AS
    SELECT indexname, indexdef FROM pg_indexes
     WHERE schemaname = current_schema() AND tablename = 'team_color_master'
       AND indexname NOT IN (SELECT c.relname FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
                              WHERE i.indrelid = 'team_color_master'::regclass AND i.indisprimary);

  EXECUTE 'DROP TABLE team_color_master';
  EXECUTE 'ALTER TABLE team_color_master_new RENAME TO team_color_master';
  IF pk_cols IS NOT NULL THEN
    EXECUTE 'ALTER TABLE team_color_master ADD CONSTRAINT team_color_master_pkey PRIMARY KEY (' || pk_cols || ')';
  END IF;
  FOR idx IN SELECT indexdef FROM _tcm_idx LOOP
    EXECUTE idx.indexdef;
  END LOOP;

  -- id の採番を続きから
  SELECT COALESCE(MAX(id), 0) INTO maxid FROM team_color_master;
  IF maxid > 0 THEN
    PERFORM setval(pg_get_serial_sequence('team_color_master', 'id'), maxid);
  END IF;
END $$;

COMMENT ON COLUMN team_color_master.link IS 'チームページのURL（country_league_master.link と同じ。同じチームの判定に使う）';
CREATE INDEX IF NOT EXISTS idx_team_color_master_link ON team_color_master (link);
CREATE INDEX IF NOT EXISTS idx_team_color_master_key  ON team_color_master (country, league, team);

-- 確認（link が register_id の直前にあること・件数が変わっていないこと）
SELECT column_name FROM information_schema.columns
 WHERE table_schema = current_schema() AND table_name = 'team_color_master' ORDER BY ordinal_position;
SELECT COUNT(*) AS rows FROM team_color_master;
COMMIT;
