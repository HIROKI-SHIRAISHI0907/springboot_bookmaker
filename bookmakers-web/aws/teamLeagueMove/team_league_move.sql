SELECT view_code, view_name, path, check_code, setup_flg, block_flg, disp_order
  FROM system_view_master WHERE check_code = 'TEAM_MOVE_UNCONFIRMED';
SELECT tgname FROM pg_trigger WHERE tgrelid = 'country_league_master'::regclass AND tgname LIKE 'trg_team_league_move%';
