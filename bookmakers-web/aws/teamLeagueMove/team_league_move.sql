-- ============================================================================
-- チーム昇格・降格確認設定（2026-11-24 追加）  soccer_bm_master で実行
--   1. team_league_move_history … チームの所属リーグが変わった記録（自動で検知 → 管理画面で確定）
--   2. country_league_master のトリガー … リーグが変わった有効なチームを 1 に記録する
--      （B004 の付け替え・シーズン終了後の生き返り・管理画面の付け替え、どれで変わっても拾う）
--   3. system_view_master … 未確定が残っていたら他の管理画面を止める（TEAM_MOVE_UNCONFIRMED）
-- 何度流しても大丈夫（IF NOT EXISTS / CREATE OR REPLACE / NOT EXISTS）。
-- ============================================================================
BEGIN;

-- 1. 移動の記録 ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS team_league_move_history (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country        TEXT         NOT NULL,
  team           TEXT         NOT NULL,
  link           TEXT,
  team_id        INTEGER,                 -- country_league_master.id
  from_league    TEXT         NOT NULL,
  to_league      TEXT         NOT NULL,
  from_level     SMALLINT,                -- 検知したときの移動元リーグのレベル（1 = 最上位）
  to_level       SMALLINT,                -- 検知したときの移動先リーグのレベル
  suggest_type   VARCHAR(10)  NOT NULL,   -- 検知したときの候補 UP（昇格）/ DOWN（降格）/ OTHER
  move_type      VARCHAR(10),             -- 確定した種類 UP / DOWN / OTHER / RENAME（リーグ名変更の付け替え）
  source         VARCHAR(10)  NOT NULL,   -- UPDATE（行の付け替え・生き返り）/ INSERT（新しい行）
  detected_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirm_time   TIMESTAMP,
  confirm_flg    CHAR(1)      NOT NULL DEFAULT '0',  -- '0' 未確定 / '1' 確定 / '9' 取り消し（誤検知）
  register_id    VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
  register_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_id      VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
  update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE  team_league_move_history IS 'チームの所属リーグの移動（昇格・降格）。country_league_master のトリガーで記録し、管理画面で確定する';
COMMENT ON COLUMN team_league_move_history.confirm_flg IS '0 未確定 / 1 確定 / 9 取り消し';
CREATE INDEX IF NOT EXISTS idx_team_league_move_history_flg  ON team_league_move_history (confirm_flg);
CREATE INDEX IF NOT EXISTS idx_team_league_move_history_team ON team_league_move_history (country, team);

-- 2. トリガー -----------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_team_league_move_detect() RETURNS trigger AS $$
DECLARE
  v_from   TEXT;
  v_source VARCHAR(10);
  v_from_level SMALLINT;
  v_to_level   SMALLINT;
  v_type   VARCHAR(10);
BEGIN
  IF NEW.del_flg IS DISTINCT FROM '0' OR NULLIF(BTRIM(NEW.league), '') IS NULL THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF OLD.league IS NOT DISTINCT FROM NEW.league OR NULLIF(BTRIM(OLD.league), '') IS NULL THEN
      RETURN NEW;
    END IF;
    v_from := OLD.league;
    v_source := 'UPDATE';
  ELSE
    -- 新しい行: 同じ国に、同じリンク（無ければ同じチーム名）の別リーグの行があれば移動とみなす（一番新しい行）
    SELECT m.league INTO v_from
      FROM country_league_master m
     WHERE m.country = NEW.country
       AND m.id <> NEW.id
       AND m.league <> NEW.league
       AND ( (NULLIF(BTRIM(NEW.link), '') IS NOT NULL AND m.link = NEW.link)
          OR (NULLIF(BTRIM(NEW.link), '') IS NULL AND m.team = NEW.team) )
     ORDER BY m.update_time DESC NULLS LAST, m.id DESC
     LIMIT 1;
    IF v_from IS NULL THEN
      RETURN NEW;
    END IF;
    v_source := 'INSERT';
  END IF;

  -- 同じ移動の未確定がすでにあれば記録しない
  IF EXISTS (SELECT 1 FROM team_league_move_history h
              WHERE h.confirm_flg = '0' AND h.country = NEW.country AND h.team = NEW.team
                AND h.from_league = v_from AND h.to_league = NEW.league) THEN
    RETURN NEW;
  END IF;

  -- リーグのレベル（この行以外の行から。動いた行の league_level は移動元のままのことがあるため）
  SELECT MIN(league_level) INTO v_from_level FROM country_league_master
   WHERE country = NEW.country AND league = v_from AND id <> NEW.id AND league_level IS NOT NULL;
  SELECT MIN(league_level) INTO v_to_level FROM country_league_master
   WHERE country = NEW.country AND league = NEW.league AND id <> NEW.id AND league_level IS NOT NULL;

  v_type := CASE
              WHEN v_from_level IS NULL OR v_to_level IS NULL THEN 'OTHER'
              WHEN v_to_level < v_from_level THEN 'UP'
              WHEN v_to_level > v_from_level THEN 'DOWN'
              ELSE 'OTHER'
            END;

  INSERT INTO team_league_move_history (
    country, team, link, team_id, from_league, to_league, from_level, to_level,
    suggest_type, move_type, source, confirm_flg,
    register_id, register_time, update_id, update_time)
  VALUES (
    NEW.country, NEW.team, NEW.link, NEW.id, v_from, NEW.league, v_from_level, v_to_level,
    v_type, v_type, v_source, '0',
    COALESCE(NEW.update_id, 'SYSTEM'), CURRENT_TIMESTAMP, COALESCE(NEW.update_id, 'SYSTEM'), CURRENT_TIMESTAMP);
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  -- 記録に失敗しても、チームマスタの更新（B004 など）は止めない
  RAISE WARNING 'fn_team_league_move_detect: %', SQLERRM;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_team_league_move_detect_upd ON country_league_master;
CREATE TRIGGER trg_team_league_move_detect_upd
  AFTER UPDATE OF league, del_flg ON country_league_master
  FOR EACH ROW EXECUTE FUNCTION fn_team_league_move_detect();

DROP TRIGGER IF EXISTS trg_team_league_move_detect_ins ON country_league_master;
CREATE TRIGGER trg_team_league_move_detect_ins
  AFTER INSERT ON country_league_master
  FOR EACH ROW EXECUTE FUNCTION fn_team_league_move_detect();

-- 3. 画面設定（未確定があれば他の管理画面を止める） ------------------------------------
--   ※ 列は既存の行に合わせています。NOT NULL の列が他にあればエラーになるので、そのときは教えてください。
INSERT INTO system_view_master (
  view_code, view_name, path, check_code, setup_flg, block_flg, disp_order, del_flg,
  register_id, register_time, update_id, update_time)
SELECT 'BM_A039', 'チーム昇格・降格確認設定', 'team-league-move', 'TEAM_MOVE_UNCONFIRMED', '1', '1',
       COALESCE(MAX(disp_order), 0) + 1, '0',
       'ADMIN', CURRENT_TIMESTAMP, 'ADMIN', CURRENT_TIMESTAMP
  FROM system_view_master
HAVING NOT EXISTS (SELECT 1 FROM system_view_master WHERE check_code = 'TEAM_MOVE_UNCONFIRMED');

